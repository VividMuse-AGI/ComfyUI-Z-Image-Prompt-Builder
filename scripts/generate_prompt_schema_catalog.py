"""Generate unified frontend schema catalog from Python source-of-truth."""

from __future__ import annotations

import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import combination_coherence  # noqa: E402
import modular_nodes  # noqa: E402
import nodes  # noqa: E402

TARGET = ROOT / "web" / "js" / "lib" / "prompt_schema_catalog.mjs"


def build_schema() -> dict:
    module_field_groups = {k: list(v) for k, v in modular_nodes.MODULE_FIELD_GROUPS.items()}
    module_node_fields = {
        name: list(modular_nodes.MODULE_FIELD_GROUPS[cls.MODULE_NAME])
        for name, cls in modular_nodes.NODE_CLASS_MAPPINGS.items()
        if issubclass(cls, modular_nodes.ZImageModuleNodeBase)
    }
    clothing_mode_fields = {k: list(v) for k, v in nodes.CLOTHING_MODE_FIELDS.items()}
    presets = {name: dict(values) for name, values in nodes.PRESETS.items()}
    coherence_rules_meta = {}
    pose_fields = list(nodes.POSE_OUTPUT_FIELDS)
    scene_fields = list(modular_nodes.MODULE_FIELD_GROUPS["场景"])
    camera_fields = list(nodes.CAMERA_OUTPUT_FIELDS)
    lighting_fields = list(nodes.LIGHTING_OUTPUT_FIELDS)
    for rule_id, meta in combination_coherence.RULE_METADATA.items():
        if rule_id == "pool_pose_classroom_location":
            fields = [*pose_fields, *scene_fields]
        elif rule_id == "camera_context":
            fields = camera_fields
        elif rule_id == "lighting_context":
            fields = lighting_fields
        else:
            fields = pose_fields
        coherence_rules_meta[rule_id] = {
            "modules": list(meta["modules"]),
            "fields": fields,
            "labels": list(meta["labels"]),
        }
    return {
        "FIELD_NAMES": list(nodes.FIELD_ORDER),
        "MODULE_FIELD_GROUPS": module_field_groups,
        "MODULE_NODE_FIELDS": module_node_fields,
        "CLOTHING_MODE_FIELDS": clothing_mode_fields,
        "MAKEUP_CUSTOM_FIELDS": list(nodes.MAKEUP_CUSTOM_FIELDS),
        "HAIR_ADVANCED_FIELDS": list(nodes.HAIR_ADVANCED_FIELDS),
        "LEGACY_PRESET_NAMES": dict(nodes.LEGACY_PRESET_NAMES),
        "LEGACY_AGE_STAGES": dict(nodes.LEGACY_AGE_STAGES),
        "THEME_OPTIONS_BY_CATEGORY": {
            k: list(v) for k, v in nodes.THEME_OPTIONS_BY_CATEGORY.items()
        },
        "ETHNICITY_BRANCHES_BY_CATEGORY": {
            k: list(v) for k, v in nodes.ETHNICITY_BRANCHES_BY_CATEGORY.items()
        },
        "SCENE_LOCATIONS_BY_CATEGORY": {
            k: list(v) for k, v in nodes.SCENE_LOCATIONS_BY_CATEGORY.items()
        },
        "SCENE_LOCATION_VALUES": list(nodes.FIELD_OPTIONS["场景地点"]),
        "PRESETS": presets,
        "COHERENCE_RULES_META": coherence_rules_meta,
    }


def render_catalog() -> str:
    return (
        "// Generated by scripts/generate_prompt_schema_catalog.py; do not edit manually.\n"
        "export const PROMPT_SCHEMA = "
        + json.dumps(build_schema(), ensure_ascii=False, indent=2)
        + ";\n"
    )


def main() -> None:
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(render_catalog(), encoding="utf-8", newline="\n")
    print(f"Generated {TARGET}")


if __name__ == "__main__":
    main()
